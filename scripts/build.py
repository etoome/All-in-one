#!/usr/bin/env python3
"""Build the release package dist/All-in-one-v<version>.zip, the only file written to dist/.

--update-url sets the page the add-in's Update button opens; the add-in itself finds new versions on GitHub.

Requires Windows with desktop PowerPoint, and "Trust access to the VBA project object model" enabled.
"""
import argparse
import base64
import contextlib
import gc
import io
import os
import re
import shutil
import subprocess
import sys
import tempfile
import time
import tomllib
import urllib.parse
import winreg
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
MODULES_DIR = ROOT / "src" / "modules"
CLASSES_DIR = ROOT / "src" / "classes"
UI_FILE = ROOT / "src" / "ui" / "customUI.xml"
ICONS_DIR = ROOT / "src" / "ui" / "icons"
INSTALLER_DIR = ROOT / "scripts" / "templates" / "installer"
DIST_DIR = ROOT / "dist"

# Hidden inside the zip so the user only sees Install.cmd and README.txt.
ZIP_SUBFOLDER = ".bin"
FAT_HIDDEN = 0x02
FAT_DIRECTORY = 0x10

DEFAULT_UPDATE_URL = "https://github.com/etoome/All-in-one/releases/latest"
# Zip comments; release.py only publishes zips marked as GitHub builds, so a custom --update-url never reaches GitHub.
GITHUB_BUILD_MARK = b"update-url=github"
CUSTOM_BUILD_MARK = b"update-url=custom"

ICON_SIZE = 32
# Button tag -> PNG whose pixels VBA rebuilds at runtime; tags without a PNG fall through to "".
ICON_TAGS = {
    "textcolor": "applyTextColor.png",
    "fillcolor": "applyFillColor.png",
    "linestyle": "applyLineStyle.png",
}

PP_LAYOUT_BLANK = 12
PP_SAVE_AS_MACRO_ENABLED = 25
MSO_AUTOMATION_SECURITY_LOW = 1

def colorize(message: str, color: str, stream) -> str:
    if not stream.isatty() or "NO_COLOR" in os.environ:
        return message
    return f"\033[{color}m{message}\033[0m"


def status(message: str) -> None:
    print(colorize(message, "90", sys.stdout))


def fail(message: str) -> None:
    sys.exit(colorize(message, "31", sys.stderr))


RELS_NS = "http://schemas.openxmlformats.org/package/2006/relationships"
CONTENT_TYPES_NS = "http://schemas.openxmlformats.org/package/2006/content-types"
CUSTOM_UI_REL_TYPE = "http://schemas.microsoft.com/office/2007/relationships/ui/extensibility"
IMAGE_REL_TYPE = "http://schemas.openxmlformats.org/officeDocument/2006/relationships/image"
PPAM_MAIN_TYPE = "application/vnd.ms-powerpoint.addin.macroEnabled.main+xml"

RELS_PART = "_rels/.rels"
CONTENT_TYPES_PART = "[Content_Types].xml"
CUSTOM_UI_PART = "customUI/customUI.xml"
CUSTOM_UI_RELS_PART = "customUI/_rels/customUI.xml.rels"
PRESENTATION_PART = "/ppt/presentation.xml"
CORE_PROPS_PART = "docProps/core.xml"
LABEL_INFO_PART = "docMetadata/LabelInfo.xml"


def resolve_version(cli_version: str | None) -> str:
    """Precedence: --version, then pyproject.toml."""
    if cli_version:
        return cli_version
    with (ROOT / "pyproject.toml").open("rb") as file:
        version = tomllib.load(file).get("project", {}).get("version")
    if not version:
        fail("No [project].version found in pyproject.toml")
    return version


def require_plain_version(version: str) -> None:
    # The add-in's update check only understands MAJOR.MINOR.PATCH, so a pre-release tag would never be offered.
    if not re.fullmatch(r"\d{1,6}\.\d{1,6}\.\d{1,6}", version):
        fail(f"Version '{version}' must look like MAJOR.MINOR.PATCH")


def require_https_url(url: str) -> None:
    # The URL is written into a VBA string literal, so anything that could end it is rejected.
    parsed = urllib.parse.urlparse(url)
    if parsed.scheme != "https" or not parsed.netloc or re.search(r'["\s\x00-\x1f]', url):
        fail(f"--update-url must be an https URL without quotes or spaces: {url!r}")


def resized_icon(path: Path, size: int) -> Image.Image:
    # Office scales oversized custom images poorly, so pre-render at the target size.
    with Image.open(path) as source:
        return source.convert("RGBA").resize((size, size), Image.Resampling.LANCZOS)


def resized_png_bytes(path: Path, size: int) -> bytes:
    buffer = io.BytesIO()
    resized_icon(path, size).save(buffer, "PNG")
    return buffer.getvalue()


def icon_bgra_base64(path: Path, size: int) -> str:
    """Straight-alpha 32bpp BGRA in bottom-up DIB row order, so VBA can rebuild the icon without decoding PNG."""
    raw = resized_icon(path, size).tobytes("raw", "BGRA")
    row_bytes = size * 4
    rows = [raw[i:i + row_bytes] for i in range(0, len(raw), row_bytes)]
    return base64.b64encode(b"".join(reversed(rows))).decode("ascii")


def write_icon_data_module(out_file: Path) -> None:
    head = [
        'Attribute VB_Name = "IconData"',
        "Option Explicit",
        "",
        "' Auto-generated by build.py from src/ui/icons PNGs. Do not edit by hand.",
        "Public Function BaseIconBase64(ByVal tag As String) As String",
        "    Select Case tag",
    ]
    body: list[str] = []
    for tag, png_name in ICON_TAGS.items():
        png = ICONS_DIR / png_name
        if not png.exists():
            continue
        b64 = icon_bgra_base64(png, ICON_SIZE)
        fn = f"Data_{tag}"
        head += [f'        Case "{tag}"', f"            BaseIconBase64 = {fn}()"]
        body += [f"Private Function {fn}() As String", "    Dim s As String"]
        # VBA allows at most 24 line continuations, so build the string with appends instead.
        body += [f'    s = s & "{b64[i:i + 800]}"' for i in range(0, len(b64), 800)]
        body += [f"    {fn} = s", "End Function", ""]
    head += ["    End Select", "End Function", ""]
    # VBA import expects ANSI text with CRLF line endings.
    with open(out_file, "w", encoding="ascii", newline="\r\n") as f:
        f.write("\n".join(head + body) + "\n")


def write_build_info_module(out_file: Path, version: str, update_url: str) -> None:
    lines = [
        'Attribute VB_Name = "BuildInfo"',
        "Option Explicit",
        "",
        "' Auto-generated by build.py. Do not edit by hand.",
        f'Public Const APP_VERSION As String = "{version}"',
        f'Public Const UPDATE_URL As String = "{update_url}"',
    ]
    with open(out_file, "w", encoding="ascii", newline="\r\n") as f:
        f.write("\n".join(lines) + "\n")


@contextlib.contextmanager
def anonymous_temp_dir():
    """Yields a TEMP folder outside the user profile; the VBE stores its MSForms.exd path (under %TEMP%) in the VBA project."""
    folder = Path(os.environ.get("PUBLIC", r"C:\Users\Public")) / "all-in-one-build"
    folder.mkdir(parents=True, exist_ok=True)
    try:
        yield folder
    finally:
        for _ in range(20):  # PowerPoint keeps files open for a moment after Quit()
            try:
                shutil.rmtree(folder)
                break
            except OSError:
                time.sleep(0.5)


def launch_powerpoint(temp_dir: Path):
    """Starts PowerPoint with TEMP/TMP set to temp_dir and attaches to it.

    A COM-activated instance is started by Windows and ignores this process's environment, so launch it directly.
    """
    import pythoncom
    import win32com.client

    with contextlib.suppress(pythoncom.com_error):
        win32com.client.GetActiveObject("PowerPoint.Application")
        fail("PowerPoint is already running; close it so the build can start its own instance.")

    app_paths = r"SOFTWARE\Microsoft\Windows\CurrentVersion\App Paths\powerpnt.exe"
    exe = winreg.QueryValue(winreg.HKEY_LOCAL_MACHINE, app_paths)
    process = subprocess.Popen([exe], env={**os.environ, "TEMP": str(temp_dir), "TMP": str(temp_dir)})
    status("Waiting for PowerPoint to start (choose No if it offers safe mode)...")
    deadline = time.monotonic() + 60
    while time.monotonic() < deadline:
        try:
            return win32com.client.GetActiveObject("PowerPoint.Application")
        except pythoncom.com_error:
            if process.poll() is not None:
                break
            time.sleep(0.5)
    fail("Could not attach to the PowerPoint instance that was started.")


def build_macro_presentation(module_files: list[Path], version: str, update_url: str, pptm_file: Path, temp_dir: Path) -> None:
    status("Launching PowerPoint...")
    ppt = launch_powerpoint(temp_dir)
    ppt.AutomationSecurity = MSO_AUTOMATION_SECURITY_LOW  # suppress macro security prompts during unattended build
    pres = None
    try:
        pres = ppt.Presentations.Add(0)  # WithWindow = msoFalse
        pres.Slides.Add(1, PP_LAYOUT_BLANK)  # PowerPoint won't SaveAs a slide-less .ppam

        with tempfile.TemporaryDirectory() as tmp:
            icon_data = Path(tmp) / "IconData.bas"
            write_icon_data_module(icon_data)
            build_info = Path(tmp) / "BuildInfo.bas"
            write_build_info_module(build_info, version, update_url)
            for module in [*module_files, icon_data, build_info]:
                status(f"Importing {module.name}...")
                pres.VBProject.VBComponents.Import(str(module))

            # SaveAs to the OpenXML add-in format (30) fails with 0x80004005, so save
            # macro-enabled and convert the package to add-in form when repackaging.
            status(f"Saving macro-enabled presentation to {pptm_file}...")
            pres.SaveAs(str(pptm_file), PP_SAVE_AS_MACRO_ENABLED)
            pres.Close()
            pres = None
    finally:
        if pres is not None:
            try:
                pres.Close()
            except Exception:
                pass
        ppt.Quit()
        del pres, ppt
        gc.collect()


def serialize_xml(root: ET.Element, default_ns: str) -> bytes:
    # Registered per call because the empty prefix can only map to one namespace at a time.
    ET.register_namespace("", default_ns)
    return ET.tostring(root, encoding="UTF-8", xml_declaration=True)


def with_ribbon_relationship(data: bytes) -> bytes:
    root = ET.fromstring(data)
    # Drop the tenant-identifying sensitivity label PowerPoint stamps on the file.
    for rel in [r for r in root if r.get("Target") == LABEL_INFO_PART]:
        root.remove(rel)
    if not any(rel.get("Type") == CUSTOM_UI_REL_TYPE for rel in root):
        ET.SubElement(root, f"{{{RELS_NS}}}Relationship", Id="rIdCustomUI", Type=CUSTOM_UI_REL_TYPE, Target=CUSTOM_UI_PART)
    return serialize_xml(root, RELS_NS)


def without_author(data: bytes) -> bytes:
    # Regex rather than ElementTree, which would rewrite the dc:/cp: prefixes as ns0:/ns1:.
    text = data.decode("utf-8")
    text = re.sub(r"(<dc:creator>).*?(</dc:creator>)", r"\1\2", text, flags=re.S)
    text = re.sub(r"(<cp:lastModifiedBy>).*?(</cp:lastModifiedBy>)", r"\1\2", text, flags=re.S)
    return text.encode("utf-8")


def as_addin_content_types(data: bytes) -> bytes:
    root = ET.fromstring(data)
    if not any(d.get("Extension") == "png" for d in root.findall(f"{{{CONTENT_TYPES_NS}}}Default")):
        ET.SubElement(root, f"{{{CONTENT_TYPES_NS}}}Default", Extension="png", ContentType="image/png")
    # Retype the main document part so the package is a PowerPoint add-in (.ppam).
    for override in root.findall(f"{{{CONTENT_TYPES_NS}}}Override"):
        if override.get("PartName") == PRESENTATION_PART:
            override.set("ContentType", PPAM_MAIN_TYPE)
        elif override.get("PartName") == f"/{LABEL_INFO_PART}":
            root.remove(override)
    return serialize_xml(root, CONTENT_TYPES_NS)


def ribbon_images_rels(images: list[Path]) -> bytes:
    # Each relationship Id is the file name without extension, matching image="..." in customUI.xml.
    root = ET.Element(f"{{{RELS_NS}}}Relationships")
    for image in images:
        ET.SubElement(root, f"{{{RELS_NS}}}Relationship", Id=image.stem, Type=IMAGE_REL_TYPE, Target=f"images/{image.name}")
    return serialize_xml(root, RELS_NS)


def inject_ribbon(pptm_file: Path, ppam_file: Path, version: str) -> None:
    status("Injecting ribbon customUI...")
    images = sorted(ICONS_DIR.glob("*.png"), key=lambda p: p.name.lower())
    ui_xml = UI_FILE.read_bytes().replace(b"@@VERSION@@", version.encode("ascii"))
    rebuild_file = ppam_file.with_name(ppam_file.name + ".rebuild")

    with zipfile.ZipFile(pptm_file) as src, zipfile.ZipFile(rebuild_file, "w", zipfile.ZIP_DEFLATED) as dest:
        for entry in src.infolist():
            if entry.filename == LABEL_INFO_PART:
                continue
            data = src.read(entry)
            if entry.filename == RELS_PART:
                data = with_ribbon_relationship(data)
            elif entry.filename == CONTENT_TYPES_PART:
                data = as_addin_content_types(data)
            elif entry.filename == CORE_PROPS_PART:
                data = without_author(data)
            dest.writestr(entry.filename, data)

        dest.writestr(CUSTOM_UI_PART, ui_xml)
        dest.writestr(CUSTOM_UI_RELS_PART, ribbon_images_rels(images))
        for image in images:
            dest.writestr(f"customUI/images/{image.name}", resized_png_bytes(image, ICON_SIZE))

    os.replace(rebuild_file, ppam_file)
    pptm_file.unlink()


def verify_package(ppam_file: Path) -> None:
    status("Verifying package...")
    with zipfile.ZipFile(ppam_file) as package:
        corrupt = package.testzip()
        if corrupt:
            fail(f"Corrupt entry '{corrupt}' in {ppam_file}")
        if CUSTOM_UI_PART not in package.namelist():
            fail(f"Ribbon part '{CUSTOM_UI_PART}' missing from package.")


def render_installer_file(name: str, version: str, update_host: str) -> str:
    text = (INSTALLER_DIR / name).read_text(encoding="utf-8")
    return text.replace("@@VERSION@@", version).replace("@@UPDATE_HOST@@", update_host)


def write_release_zip(ppam_file: Path, version: str, update_url: str, mark: bytes) -> Path:
    status("Writing release package...")
    zip_file = DIST_DIR / f"All-in-one-v{version}.zip"
    folder = zipfile.ZipInfo(f"{ZIP_SUBFOLDER}/", date_time=time.localtime()[:6])
    folder.create_system = 0  # FAT attributes are what Explorer and 7-Zip read the hidden flag from
    folder.external_attr = FAT_HIDDEN | FAT_DIRECTORY
    update_host = urllib.parse.urlparse(update_url).hostname
    install_cmd = render_installer_file("Install.cmd", version, update_host).replace("\r\n", "\n").replace("\n", "\r\n")
    readme = render_installer_file("README.txt", version, update_host).replace("\r\n", "\n").replace("\n", "\r\n")
    with zipfile.ZipFile(zip_file, "w", zipfile.ZIP_DEFLATED) as package:
        package.comment = mark
        package.writestr(folder, b"")
        package.write(ppam_file, f"{ZIP_SUBFOLDER}/{ppam_file.name}")
        package.writestr(f"{ZIP_SUBFOLDER}/Install.ps1", render_installer_file("Install.ps1", version, update_host))
        package.writestr("Install.cmd", install_cmd.encode("ascii"))
        package.writestr("README.txt", readme.encode("ascii"))
    return zip_file


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--version", help="release version (default: pyproject.toml)")
    parser.add_argument("--update-url", default=DEFAULT_UPDATE_URL, help="page opened by the Update button (default: %(default)s)")
    args = parser.parse_args()
    version = resolve_version(args.version)
    require_plain_version(version)
    require_https_url(args.update_url)

    if not UI_FILE.exists():
        fail(f"Ribbon XML not found: {UI_FILE}")
    module_files = sorted(MODULES_DIR.glob("*.bas")) + sorted(CLASSES_DIR.glob("*.cls"))
    if not module_files:
        fail(f"No .bas/.cls modules found in {MODULES_DIR} or {CLASSES_DIR}")

    shutil.rmtree(DIST_DIR, ignore_errors=True)
    DIST_DIR.mkdir(parents=True)

    # Intermediates live in the build's temp folder, which is deleted afterwards, so dist/ only holds the zip.
    with anonymous_temp_dir() as temp_dir:
        pptm_file = temp_dir / "All-in-one.pptm"
        ppam_file = temp_dir / f"All-in-one-v{version}.ppam"
        build_macro_presentation(module_files, version, args.update_url, pptm_file, temp_dir)
        inject_ribbon(pptm_file, ppam_file, version)
        verify_package(ppam_file)
        mark = GITHUB_BUILD_MARK if args.update_url == DEFAULT_UPDATE_URL else CUSTOM_BUILD_MARK
        zip_file = write_release_zip(ppam_file, version, args.update_url, mark)

    print(colorize(f"Release package: {zip_file}", "32", sys.stdout))
    return 0


if __name__ == "__main__":
    sys.exit(main())
