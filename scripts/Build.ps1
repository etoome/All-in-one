# Batch files are safest as ASCII with no BOM; the rest as UTF-8 without a BOM.
$utf8NoBom = New-Object System.Text.UTF8Encoding($false)

$zip = [System.IO.Compression.ZipFile]::Open($zipFile, [System.IO.Compression.ZipArchiveMode]::Create)
try {
    # Explorer and 7-Zip honor this hidden flag on extract; Expand-Archive ignores it (Install.cmd re-applies it).
    $dirEntry = $zip.CreateEntry("$subFolder/")
    $dirEntry.ExternalAttributes = 0x12
    Write-ZipEntry -DestArchive $zip -PartName 'Install.cmd' -Bytes ([System.Text.Encoding]::ASCII.GetBytes($installCmdContent))
    Write-ZipEntry -DestArchive $zip -PartName 'README.md'   -Bytes ($utf8NoBom.GetBytes($readmeContent.Replace('@@VERSION@@', $version)))
    Write-ZipEntry -DestArchive $zip -PartName "$subFolder/Install.ps1" -Bytes ($utf8NoBom.GetBytes($installPs1Content.Replace('@@VERSION@@', $version)))
    [System.IO.Compression.ZipFileExtensions]::CreateEntryFromFile($zip, $outputFile, "$subFolder/$ppamName") | Out-Null
}
finally {
    $zip.Dispose()
}

Remove-Item -Path $outputFile -Force

Write-Host "Release zip: $zipFile"
