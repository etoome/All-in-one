# Copy a source zip entry into another archive, decompressing then recompressing
# (never ZipArchiveMode.Update on an OOXML package -- it corrupts data-descriptor entries).
function Copy-ZipEntry {
    param($SourceEntry, $DestArchive)
    $newEntry = $DestArchive.CreateEntry($SourceEntry.FullName)
    $inStream  = $SourceEntry.Open()
    $outStream = $newEntry.Open()
    try { $inStream.CopyTo($outStream) } finally { $outStream.Dispose(); $inStream.Dispose() }
}

function Write-ZipEntry {
    param($DestArchive, [string]$PartName, [byte[]]$Bytes)
    $entry = $DestArchive.CreateEntry($PartName)
    $stream = $entry.Open()
    try { $stream.Write($Bytes, 0, $Bytes.Length) } finally { $stream.Dispose() }
}

# Downscale a PNG to a square ribbon-icon size with anti-aliasing. Office scales oversized
# custom images with a low-quality algorithm, so pre-render at the target size to stay crisp.
function Get-ResizedPngBytes {
    param([string]$Path, [int]$Size)
    $source = [System.Drawing.Image]::FromFile($Path)
    $bitmap = New-Object System.Drawing.Bitmap($Size, $Size, [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
    $graphics = [System.Drawing.Graphics]::FromImage($bitmap)
    $stream = New-Object System.IO.MemoryStream
    try {
        $graphics.InterpolationMode  = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
        $graphics.SmoothingMode      = [System.Drawing.Drawing2D.SmoothingMode]::HighQuality
        $graphics.PixelOffsetMode    = [System.Drawing.Drawing2D.PixelOffsetMode]::HighQuality
        $graphics.CompositingQuality = [System.Drawing.Drawing2D.CompositingQuality]::HighQuality
        $graphics.Clear([System.Drawing.Color]::Transparent)
        $graphics.DrawImage($source, 0, 0, $Size, $Size)
        $bitmap.Save($stream, [System.Drawing.Imaging.ImageFormat]::Png)
        return $stream.ToArray()
    }
    finally {
        $graphics.Dispose(); $bitmap.Dispose(); $source.Dispose(); $stream.Dispose()
    }
}

# Decode a PNG to straight-alpha 32bpp BGRA in bottom-up DIB row order, Base64-encoded,
# so VBA can rebuild the icon without decoding PNG.
function Get-IconBgraBase64 {
    param([string]$Path, [int]$Size)
    $resized = Get-ResizedPngBytes -Path $Path -Size $Size
    $stream  = New-Object System.IO.MemoryStream (,$resized)
    $bitmap  = New-Object System.Drawing.Bitmap($stream)
    try {
        $rect = New-Object System.Drawing.Rectangle(0, 0, $Size, $Size)
        $data = $bitmap.LockBits($rect, [System.Drawing.Imaging.ImageLockMode]::ReadOnly, [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
        try {
            $stride = $data.Stride
            $top    = New-Object byte[] ($stride * $Size)
            [System.Runtime.InteropServices.Marshal]::Copy($data.Scan0, $top, 0, $top.Length)
        }
        finally { $bitmap.UnlockBits($data) }
        $rowBytes = $Size * 4
        $out = New-Object byte[] ($rowBytes * $Size)
        for ($y = 0; $y -lt $Size; $y++) {
            [Array]::Copy($top, ($Size - 1 - $y) * $stride, $out, $y * $rowBytes, $rowBytes)
        }
        return [System.Convert]::ToBase64String($out)
    }
    finally { $bitmap.Dispose(); $stream.Dispose() }
}

# Generates IconData.bas: button tag -> base icon pixels (Base64). Tags without a PNG fall through to "".
function New-IconDataModule {
    param([string]$OutFile, [string]$IconsDir)
    $map = [ordered]@{ 'textcolor' = 'textColorFormatting.png'; 'fillcolor' = 'fillColorFormatting.png'; 'linestyle' = 'lineStyleFormatting.png' }
    $head = New-Object System.Text.StringBuilder
    $body = New-Object System.Text.StringBuilder
    [void]$head.AppendLine('Attribute VB_Name = "IconData"')
    [void]$head.AppendLine('Option Explicit')
    [void]$head.AppendLine('')
    [void]$head.AppendLine("' Auto-generated by Build.ps1 from src/ui/icons PNGs. Do not edit by hand.")
    [void]$head.AppendLine('Public Function BaseIconBase64(ByVal tag As String) As String')
    [void]$head.AppendLine('    Select Case tag')
    foreach ($tag in $map.Keys) {
        $png = Join-Path $IconsDir $map[$tag]
        if (-not (Test-Path $png)) { continue }
        $b64 = Get-IconBgraBase64 -Path $png -Size 32
        $fn  = "Data_$tag"
        [void]$head.AppendLine("        Case ""$tag""")
        [void]$head.AppendLine("            BaseIconBase64 = $fn()")
        [void]$body.AppendLine("Private Function $fn() As String")
        [void]$body.AppendLine('    Dim s As String')
        # VBA allows at most 24 line continuations, so build the string with appends instead.
        for ($i = 0; $i -lt $b64.Length; $i += 800) {
            $chunk = $b64.Substring($i, [Math]::Min(800, $b64.Length - $i))
            [void]$body.AppendLine("    s = s & `"$chunk`"")
        }
        [void]$body.AppendLine("    $fn = s")
        [void]$body.AppendLine('End Function')
        [void]$body.AppendLine('')
    }
    [void]$head.AppendLine('    End Select')
    [void]$head.AppendLine('End Function')
    [void]$head.AppendLine('')
    [System.IO.File]::WriteAllText($OutFile, $head.ToString() + $body.ToString(), [System.Text.Encoding]::Default)
}

$repoRoot      = Split-Path -Parent $PSScriptRoot
$modulesDir    = Join-Path $repoRoot 'src\modules'
$classesDir    = Join-Path $repoRoot 'src\classes'
$uiFile        = Join-Path $repoRoot 'src\ui\customUI.xml'
$imagesDir     = Join-Path $repoRoot 'src\ui\icons'
$distDir       = Join-Path $repoRoot 'dist'
$outputFile    = Join-Path $distDir 'All-in-one.ppam'
$pptmFile      = Join-Path $distDir 'All-in-one.pptm'
# Date-based version so each build produces a distinctly named release archive.
$version       = Get-Date -Format 'yyyy.MM.dd'
$zipFile       = Join-Path $distDir "All-in-one-v$version.zip"

if (-not (Test-Path $uiFile)) { throw "Ribbon XML not found: $uiFile" }
$moduleFiles = @(Get-ChildItem -Path $modulesDir -Filter '*.bas' -File)
if (Test-Path $classesDir) { $moduleFiles += @(Get-ChildItem -Path $classesDir -Filter '*.cls' -File) }
if (-not $moduleFiles) { throw "No .bas modules found in $modulesDir or $classesDir" }

if (Test-Path $distDir) { Remove-Item -Path $distDir -Recurse -Force }
New-Item -ItemType Directory -Path $distDir -Force | Out-Null

Write-Host "Launching PowerPoint..."
$ppt = New-Object -ComObject PowerPoint.Application
$ppt.AutomationSecurity = 1  # msoAutomationSecurityLow: suppress macro security prompts during unattended build

$pres = $null
try {
    $pres = $ppt.Presentations.Add($false)  # WithWindow = msoFalse
    $pres.Slides.Add(1, 12) | Out-Null  # ppLayoutBlank: PowerPoint won't SaveAs a slide-less .ppam

    Add-Type -AssemblyName System.Drawing
    $iconDataFile = Join-Path ([System.IO.Path]::GetTempPath()) 'IconData.bas'
    New-IconDataModule -OutFile $iconDataFile -IconsDir $imagesDir
    $moduleFiles = @($moduleFiles) + @(Get-Item $iconDataFile)

    foreach ($module in $moduleFiles) {
        Write-Host "Importing $($module.Name)..."
        $pres.VBProject.VBComponents.Import($module.FullName) | Out-Null
    }

    # PowerPoint automation cannot SaveAs the OpenXML add-in format directly
    # (ppSaveAsOpenXMLAddin=30 fails with 0x80004005), so save macro-enabled and
    # convert the package to add-in form during the repackage step below.
    Write-Host "Saving macro-enabled presentation to $pptmFile..."
    $pres.SaveAs($pptmFile, 25)  # ppSaveAsOpenXMLPresentationMacroEnabled
    $pres.Close()
    $pres = $null
}
finally {
    if ($pres) { try { $pres.Close() } catch { } }
    $ppt.Quit()
    [void][System.Runtime.InteropServices.Marshal]::ReleaseComObject($ppt)
    $ppt = $null
    [System.GC]::Collect()
    [System.GC]::WaitForPendingFinalizers()
}

# Inject the ribbon customization part. PowerPoint's package uses data descriptors on
# some entries that ZipArchiveMode.Update silently corrupts, so rebuild from scratch.
Write-Host "Injecting ribbon customUI..."
Add-Type -AssemblyName System.IO.Compression
Add-Type -AssemblyName System.IO.Compression.FileSystem
Add-Type -AssemblyName System.Drawing

$relsPath        = '_rels/.rels'
$contentTypesPart = '[Content_Types].xml'
$customUiPart    = 'customUI/customUI.xml'
$customUiRelsPart = 'customUI/_rels/customUI.xml.rels'
$customUiRelNs   = 'http://schemas.microsoft.com/office/2007/relationships/ui/extensibility'
$presentationPart = '/ppt/presentation.xml'
$ppamMainType    = 'application/vnd.ms-powerpoint.addin.macroEnabled.main+xml'
$rebuildFile     = "$outputFile.rebuild"
if (Test-Path $rebuildFile) { Remove-Item $rebuildFile -Force }

$uiBytes     = [System.IO.File]::ReadAllBytes($uiFile)
$imageFiles  = @(Get-ChildItem -Path $imagesDir -Filter '*.png' -File -ErrorAction SilentlyContinue | Sort-Object Name)

# Generate the ribbon relationships part from the images on disk. Each image's
# relationship Id is its file name without extension, matching the image="..."
# references in customUI.xml.
$imageRelNs = 'http://schemas.openxmlformats.org/officeDocument/2006/relationships/image'
$relsSb = New-Object System.Text.StringBuilder
[void]$relsSb.AppendLine('<?xml version="1.0" encoding="UTF-8" standalone="yes"?>')
[void]$relsSb.AppendLine('<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">')
foreach ($image in $imageFiles) {
    $relId = [System.IO.Path]::GetFileNameWithoutExtension($image.Name)
    [void]$relsSb.AppendLine("  <Relationship Id=`"$relId`" Type=`"$imageRelNs`" Target=`"images/$($image.Name)`" />")
}
[void]$relsSb.AppendLine('</Relationships>')
$uiRelsBytes = [System.Text.Encoding]::UTF8.GetBytes($relsSb.ToString())

$src  = [System.IO.Compression.ZipFile]::OpenRead($pptmFile)
$dest = [System.IO.Compression.ZipFile]::Open($rebuildFile, [System.IO.Compression.ZipArchiveMode]::Create)
try {
    foreach ($entry in $src.Entries) {
        if ($entry.FullName -eq $relsPath) {
            $reader = New-Object System.IO.StreamReader($entry.Open())
            try { $relsXml = [xml]$reader.ReadToEnd() } finally { $reader.Dispose() }

            if (-not ($relsXml.Relationships.Relationship | Where-Object { $_.Type -eq $customUiRelNs })) {
                $rel = $relsXml.CreateElement('Relationship', $relsXml.Relationships.NamespaceURI)
                $rel.SetAttribute('Id', 'rIdCustomUI')
                $rel.SetAttribute('Type', $customUiRelNs)
                $rel.SetAttribute('Target', $customUiPart)
                [void]$relsXml.Relationships.AppendChild($rel)
            }

            $newEntry = $dest.CreateEntry($entry.FullName)
            $writer = New-Object System.IO.StreamWriter($newEntry.Open())
            try { $relsXml.Save($writer) } finally { $writer.Dispose() }
        }
        elseif ($entry.FullName -eq $contentTypesPart) {
            $reader = New-Object System.IO.StreamReader($entry.Open())
            try { $ctXml = [xml]$reader.ReadToEnd() } finally { $reader.Dispose() }

            if (-not ($ctXml.Types.Default | Where-Object { $_.Extension -eq 'png' })) {
                $def = $ctXml.CreateElement('Default', $ctXml.Types.NamespaceURI)
                $def.SetAttribute('Extension', 'png')
                $def.SetAttribute('ContentType', 'image/png')
                [void]$ctXml.Types.AppendChild($def)
            }

            # Retype the main document part so the package is a PowerPoint add-in (.ppam).
            $mainOverride = @($ctXml.Types.Override | Where-Object { $_.PartName -eq $presentationPart })
            if ($mainOverride.Count -gt 0) { $mainOverride[0].ContentType = $ppamMainType }

            $newEntry = $dest.CreateEntry($entry.FullName)
            $writer = New-Object System.IO.StreamWriter($newEntry.Open())
            try { $ctXml.Save($writer) } finally { $writer.Dispose() }
        }
        else {
            Copy-ZipEntry -SourceEntry $entry -DestArchive $dest
        }
    }

    Write-ZipEntry -DestArchive $dest -PartName $customUiPart -Bytes $uiBytes
    Write-ZipEntry -DestArchive $dest -PartName $customUiRelsPart -Bytes $uiRelsBytes

    foreach ($image in $imageFiles) {
        $imageBytes = Get-ResizedPngBytes -Path $image.FullName -Size 32
        Write-ZipEntry -DestArchive $dest -PartName "customUI/images/$($image.Name)" -Bytes $imageBytes
    }
}
finally {
    $dest.Dispose()
    $src.Dispose()
}

Move-Item -Path $rebuildFile -Destination $outputFile -Force
Remove-Item -Path $pptmFile -Force

# Verify every entry decompresses to its declared length and the ribbon part is present.
Write-Host "Verifying package..."
$verify = [System.IO.Compression.ZipFile]::OpenRead($outputFile)
try {
    $hasCustomUi = $false
    foreach ($entry in $verify.Entries) {
        if ($entry.FullName -eq $customUiPart) { $hasCustomUi = $true }
        $ms = New-Object System.IO.MemoryStream
        $es = $entry.Open()
        try { $es.CopyTo($ms) } finally { $es.Dispose() }
        if ($entry.Length -ne $ms.Length) {
            throw "Corrupt entry '$($entry.FullName)': declared $($entry.Length) bytes, decompressed $($ms.Length)."
        }
        $ms.Dispose()
    }
    if (-not $hasCustomUi) { throw "Ribbon part '$customUiPart' missing from package." }
}
finally {
    $verify.Dispose()
}

Write-Host "Packaging release zip..."
if (Test-Path $zipFile) { Remove-Item $zipFile -Force }

